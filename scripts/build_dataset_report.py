#!/usr/bin/env python3
"""Assemble data/evaluation/dataset_report.md from the generated pipeline outputs (no new analysis).

    .venv/bin/python scripts/build_dataset_report.py
"""
from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"


def load_jsonl(path: Path) -> list[dict]:
    return [json.loads(x) for x in path.open()] if path.exists() else []


def main() -> None:
    rows = list(csv.DictReader((DATA / "manifest.csv").open(newline="")))
    contracts = [r for r in rows if r["data_category"] == "contract"]
    lines = ["# SlipSlopes dataset report", "",
             "Generated by `scripts/build_dataset_report.py` from the pipeline outputs. Regenerate with "
             "`.venv/bin/python scripts/prepare_data.py`.", "",
             "## Contract documents", "",
             "| document_id | type | source_type | pages | blank pages | OCR needed | candidates | auto rules | status |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in contracts:
        s_path = DATA / "interim" / "extracted_text" / r["document_id"] / "summary.json"
        s = json.loads(s_path.read_text()) if s_path.exists() else {}
        lines.append(f"| {r['document_id']} | {r['document_type']} | {r['source_type']} | {s.get('pages_total', '-')} | "
                     f"{len(s.get('blank_pages_no_images', [])) if s else '-'} | "
                     f"{'yes' if s.get('ocr_required') else 'no' if s else '-'} | {s.get('candidate_passages', '-')} | "
                     f"{s.get('auto_rules', '-')} | {r['extraction_status']} |")
    real = sum(1 for r in contracts if r["source_type"] == "real_public" and r["extraction_status"] != "missing")
    synth = sum(1 for r in contracts if r["source_type"] == "synthetic")
    missing = [r["document_id"] for r in contracts if r["extraction_status"] == "missing"]
    lines += ["", f"Real public contract documents available: **{real}**. Synthetic sample contracts: **{synth}**. "
              f"Missing: {', '.join(missing) or 'none'}.", "",
              "*Candidates* are keyword-matched sentences for human review - not rules. *Auto rules* come from the "
              "deterministic rule-based extractor in `backend/app/engine` and are all `unverified`; it only recognises "
              "BREIT-style repurchase clauses and the synthetic sample contracts.", ""]

    checks = json.loads((DATA / "evaluation" / "quote_checks.json").read_text())
    cases = load_jsonl(DATA / "labels" / "evaluation_cases.jsonl")
    by_doc = Counter(c["document_id"] for c in cases)
    by_type = Counter(c["expected_constraint_type"] for c in cases)
    ok = sum(1 for c in checks if c["quote_check"] in ("exact", "case_insensitive"))
    lines += ["## Evaluation set", "",
              f"- `labels/evaluation_cases.jsonl`: {len(cases)} cases from real documents ({dict(by_doc)}).",
              f"- Constraint types covered: {dict(by_type)}.",
              "- `labels/extraction_examples.jsonl`: few-shot examples taken only from synthetic contracts.",
              f"- Quote check: {ok}/{len(checks)} clause texts found verbatim on their cited PDF page.",
              "- Status `source_checked` means the value and conditions were read against the cited page during "
              "preparation; no case is `human_verified` yet.", ""]

    prof = json.loads((DATA / "interim" / "normalized_finance" / "finance_profile.json").read_text())
    lines += ["## Client-finance data", ""]
    for doc_id, p in prof.items():
        lines += [f"### {doc_id} - `{p['file']}`", "", f"- Shape: {p['rows']} rows x {p['columns']} columns; "
                  f"duplicate rows: {p['duplicate_rows']}; missing values: {p['missing'] or 'none'}",
                  f"- Source/license: {p['license_source_status']}", "", "| column | type | min | median | max |",
                  "|---|---|---|---|---|"]
        for col, t in p["dtypes"].items():
            rng = p["numeric_ranges"].get(col)
            lines.append(f"| {col} | {t} | " + (" | ".join(f"{rng[k]:,.2f}" for k in ("min", "median", "max"))
                                                 if rng else " |  | ") + " |")
        lines += ["", "Checks:"] + [f"- {c}" for c in p["checks"]] + [""]

    lines += ["## Known gaps and cautions", "",
              "- No RSU award agreement (real) is available; only the synthetic RSU grant exists.",
              "- Source URLs were recorded only where recoverable from the files (one SEC filing). Other download URLs "
              "and all Kaggle/source identifiers and licenses are unknown and must be confirmed before redistribution.",
              "- The personal-finance dataset is synthetic, individual-level and has no monthly history, assets, "
              "holdings or obligations beyond one loan; it must not be presented as real client data.",
              "- Three real contracts are browser prints of SEC HTML; their page numbers are print pages.",
              "- The UBS credit line agreement states no numeric collateral maintenance level or advance rate.",
              "- The Parkway LPA is a real-estate office fund agreement (2008), not a private-equity buyout LPA.", ""]
    out = DATA / "evaluation" / "dataset_report.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
